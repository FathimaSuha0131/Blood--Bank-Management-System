    private void idActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_idActionPerformed
        // TODO add your handling code here:
       try {

        if(id.getSelectedItem() == null) {
            return;
        }

        String donorID = id.getSelectedItem().toString();


        if(id.getSelectedItem()==null || id.getSelectedIndex()==0)
{
    selectbloodgroup.setSelectedIndex(0);
    return;
}

        Connection con = connectionprovider.getCon();

        PreparedStatement ps = con.prepareStatement(
            "SELECT bloodGroup FROM donor WHERE donorID=?"
        );

        ps.setInt(1, Integer.parseInt(donorID));


        ResultSet rs = ps.executeQuery();


        if(rs.next()) {

            String bloodGroup = rs.getString("bloodGroup");

            selectbloodgroup.setSelectedItem(bloodGroup);

        }


    } catch(Exception e) {

        JOptionPane.showMessageDialog(null,e);

    }
    }//GEN-LAST:event_idActionPerformed

    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        // TODO add your handling code here:
         try {

        // Get values from form
        String donorID = id.getSelectedItem().toString();
        String bloodGroup = selectbloodgroup.getSelectedItem().toString();

        int qty = Integer.parseInt(quantity.getText());

        String donationDate = date.getText();


        // Database connection
        Connection con = connectionprovider.getCon();


      PreparedStatement ps1 = con.prepareStatement(
    "SELECT stockID FROM stock WHERE bloodGroup=?"
);

ps1.setString(1, bloodGroup);

ResultSet rs = ps1.executeQuery();

int stockID = 0;

if (rs.next()) {

    stockID = rs.getInt("stockID");

} else {

    JOptionPane.showMessageDialog(
        this,
        "Blood Group Not Found"
    );

    return;
}



        // Insert Donation
        PreparedStatement ps2 = con.prepareStatement(
            "INSERT INTO donation "
    + "(donorID,stockID,bloodGroup,quantity,donationDate) "
    + "VALUES(?,?,?,?,?)"
);

       ps2.setInt(1, Integer.parseInt(donorID));
ps2.setInt(2, stockID);
ps2.setString(3, bloodGroup);
ps2.setInt(4, qty);
ps2.setString(5, donationDate);

int insert = ps2.executeUpdate();


        if(insert > 0) {


            // Increase Blood Stock
            PreparedStatement ps3 = con.prepareStatement(
                "UPDATE stock "
    + "SET units = units + ? "
    + "WHERE stockID=?"
            );


           ps3.setInt(1, qty);
ps3.setInt(2, stockID);


           ps3.executeUpdate();

ps3.close();


            JOptionPane.showMessageDialog(
                null,
                "Donation Added Successfully"
            );



            // Clear fields

            id.setSelectedIndex(0);

            selectbloodgroup.setSelectedIndex(0);

            quantity.setText("");

            date.setText("");

        }


    } catch(NumberFormatException e) {


        JOptionPane.showMessageDialog(
            null,
            "Enter valid quantity"
        );


    } catch(Exception e) {


        JOptionPane.showMessageDialog(
            null,
            e
        );

    }

    }//GEN-LAST:event_saveActionPerformed

