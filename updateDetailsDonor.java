    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
        // TODO add your handling code here:
        String donorId = donorid.getText().trim();

    if (donorId.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter Donor ID"
        );
        return;
    }

    try {
        Connection con = connectionprovider.getCon();

        String sql = "SELECT * FROM donor WHERE donorID = ?";
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, Integer.parseInt(donorId));

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            fullname.setText(rs.getString("name"));
            fathername.setText(rs.getString("fatherName"));
            mothername.setText(rs.getString("motherName"));
            dateofbirth.setText(rs.getString("DOB"));
            mobileno.setText(rs.getString("MobileNo"));
            gender.setText(rs.getString("gender"));
            email.setText(rs.getString("email"));
            bloodgroup.setText(rs.getString("bloodGroup"));
            city.setText(rs.getString("city"));
            address.setText(rs.getString("address"));

            donorid.setEditable(false);
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Donor ID not found"
            );
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error: " + e.getMessage()
        );
        e.printStackTrace();
    }
        
    }//GEN-LAST:event_searchActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
    String donorIdValue = donorid.getText().trim();
    String fullNameValue = fullname.getText().trim();
    String fatherNameValue = fathername.getText().trim();
    String motherNameValue = mothername.getText().trim();
    String dobValue = dateofbirth.getText().trim();   // Corrected
    String mobileNoValue = mobileno.getText().trim();
    String genderValue = gender.getText().trim();
    String emailValue = email.getText().trim();
    String bloodGroupValue = bloodgroup.getText().trim();
    String cityValue = city.getText().trim();
    String addressValue = address.getText().trim();

    if (donorIdValue.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please search Donor ID first.");
        return;
    }

    try {
        Connection con = connectionprovider.getCon();

        String sql = "UPDATE donor SET name=?, fatherName=?, motherName=?, DOB=?, MobileNo=?, gender=?, email=?, bloodGroup=?, city=?, address=? WHERE donorID=?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, fullNameValue);
        pst.setString(2, fatherNameValue);
        pst.setString(3, motherNameValue);
        pst.setString(4, dobValue);
        pst.setString(5, mobileNoValue);
        pst.setString(6, genderValue);
        pst.setString(7, emailValue);
        pst.setString(8, bloodGroupValue);
        pst.setString(9, cityValue);
        pst.setString(10, addressValue);
        pst.setInt(11, Integer.parseInt(donorIdValue));

        int i = pst.executeUpdate();

        if (i > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Donor Details Updated Successfully");
            setVisible(false);
            new updateDetailsDonor().setVisible(true);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Update Failed");
        }

    } 
    catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, e);
    }

        
    }//GEN-LAST:event_jButton2ActionPerformed

