    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String donorId = donorid.getText();
        try {
            Connection con = connectionprovider.getCon();
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("select * from donor where donorId='" + donorId + "'");
            if (rs.next()) {
                fullname.setText(rs.getString(2));
                fathername.setText(rs.getString(3));
                mothername.setText(rs.getString(4));
                dob.setText(rs.getString(5));
                mobilenumber.setText(rs.getString(6));
                gender.setText(rs.getString(7));
                email.setText(rs.getString(8));
                bloodgroup.setText(rs.getString(9));
                city.setText(rs.getString(10));
                address.setText(rs.getString(11));
                donorid.setEditable(false);
            } else {
                JOptionPane.showMessageDialog(null, "Donor Id does not exist");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
       
    int a = JOptionPane.showConfirmDialog(
            null,
            "Do you really want to delete this donor?",
            "Select",
            JOptionPane.YES_NO_OPTION);

    if (a == 0) {

        String donor = donorid.getText();

        try {
            Connection con = connectionprovider.getCon();
            PreparedStatement ps = con.prepareStatement(
                    "DELETE FROM donor WHERE donorId=?");

            ps.setString(1, donor);

            int row = ps.executeUpdate();

            if (row > 0) {
                JOptionPane.showMessageDialog(null, "Donor Deleted Successfully");
                setVisible(false);
                new deleteDonor().setVisible(true);
            } else {
                JOptionPane.showMessageDialog(null, "Donor not found");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

