    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
                                                
    String donorID = donorid.getText().trim();
    String name = fullname.getText().trim();
    String fatherName = fathername.getText().trim();
    String motherName = mothername.getText().trim();

    SimpleDateFormat dFormat = new SimpleDateFormat("dd-MM-yyyy");
    String DOB = "";

    if (dateofbirth.getDate() != null) {
        DOB = dFormat.format(dateofbirth.getDate());
    }

    String mobileNo = mobileno.getText().trim();
    String Gender = (String) gender.getSelectedItem();
    String Email = email.getText().trim();
    String BloodGroup = (String) bloodgroup.getSelectedItem();
    String City = city.getText().trim();
    String Address = address.getText().trim();

    // ==============================
    // CHECK EMPTY FIELDS
    // ==============================

    if (name.isEmpty() || fatherName.isEmpty() || motherName.isEmpty()
            || DOB.isEmpty() || mobileNo.isEmpty() || Email.isEmpty()
            || City.isEmpty() || Address.isEmpty()) {

        JOptionPane.showMessageDialog(null,
                "Please fill in all details before saving!");
        return;
    }

    // ==============================
    // FULL NAME - TEXT ONLY
    // ==============================

    if (!name.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(null,
                "Full Name must contain letters only!");
        fullname.requestFocus();
        return;
    }

    // ==============================
    // FATHER NAME - TEXT ONLY
    // ==============================

    if (!fatherName.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(null,
                "Father Name must contain letters only!");
        fathername.requestFocus();
        return;
    }

    // ==============================
    // MOTHER NAME - TEXT ONLY
    // ==============================

    if (!motherName.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(null,
                "Mother Name must contain letters only!");
        mothername.requestFocus();
        return;
    }

    // ==============================
    // MOBILE NUMBER - INTEGER ONLY
    // ==============================

    if (!mobileNo.matches("\\d+")) {
        JOptionPane.showMessageDialog(null,
                "Mobile No must contain numbers only!");
        mobileno.requestFocus();
        return;
    }

    // ==============================
    // MOBILE NUMBER - 10 DIGITS
    // ==============================

    if (mobileNo.length() != 10) {
        JOptionPane.showMessageDialog(null,
                "Mobile No must contain exactly 10 digits!");
        mobileno.requestFocus();
        return;
    }

    // ==============================
    // CITY - TEXT ONLY
    // ==============================

    if (!City.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(null,
                "City must contain letters only!");
        city.requestFocus();
        return;
    }

    // ==============================
    // EMAIL VALIDATION
    // ==============================

    if (!Email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
        JOptionPane.showMessageDialog(null,
                "Please enter a valid Email address!");
        email.requestFocus();
        return;
    }

    // ==============================
    // SAVE TO DATABASE
    // ==============================

    try {

        Connection con = project.connectionprovider.getCon();
        Statement st = con.createStatement();

        String sqlQuery = "INSERT INTO donor VALUES('"
                + donorID + "','"
                + name + "','"
                + fatherName + "','"
                + motherName + "','"
                + DOB + "','"
                + mobileNo + "','"
                + Gender + "','"
                + Email + "','"
                + BloodGroup + "','"
                + City + "','"
                + Address + "')";

        st.executeUpdate(sqlQuery);

        JOptionPane.showMessageDialog(null,
                "Donor Details Saved Successfully!");

        setVisible(false);
        new addNewDonor().setVisible(true);

    } catch (HeadlessException | SQLException e) {
        JOptionPane.showMessageDialog(null, e);
    }

    }//GEN-LAST:event_jButton1ActionPerformed

