    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String bloodGroup = jComboBox1.getSelectedItem().toString();

int decrease;

try {

    decrease = Integer.parseInt(jTextField1.getText());

    Connection con = connectionprovider.getCon();

    // Check current stock first
    PreparedStatement check = con.prepareStatement(
        "SELECT units FROM stock WHERE bloodGroup=?"
    );

    check.setString(1, bloodGroup);

    ResultSet rsCheck = check.executeQuery();


    if(rsCheck.next()) {

        int currentStock = rsCheck.getInt("units");


        if(decrease <= currentStock) {


            PreparedStatement ps = con.prepareStatement(
               "UPDATE stock SET units = units - ? WHERE bloodGroup=?"
            );


            ps.setInt(1, decrease);
            ps.setString(2, bloodGroup);


            int result = ps.executeUpdate();


            if(result > 0) {

                JOptionPane.showMessageDialog(
                    null,
                    "Stock Decreased Successfully"
                );


                // Refresh JTable

                Statement st = con.createStatement();

                ResultSet rs = st.executeQuery(
                   "SELECT bloodGroup, units FROM stock"
                );


                jTable1.setModel(
                    DbUtils.resultSetToTableModel(rs)
                );


                jTextField1.setText("");

            }

        } else {

            JOptionPane.showMessageDialog(
                null,
                "Not enough blood units available"
            );

        }


    } else {

        JOptionPane.showMessageDialog(
            null,
            "Blood Group Not Found"
        );

    }


} catch(NumberFormatException e) {

    JOptionPane.showMessageDialog(
        null,
        "Enter valid units"
    );


} catch(Exception e) {

    JOptionPane.showMessageDialog(
        null,
        e
    );

}
    }//GEN-LAST:event_jButton1ActionPerformed

