    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    try {
        // 1. Create a temporary CSV file
        File csvFile = File.createTempFile("Donor_Location_Report_", ".csv");
        csvFile.deleteOnExit();

        // Target jTable2 where location search data is loaded
        TableModel model = jTable2.getModel();
        
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No donor data available in the table!");
            return;
        }

        FileWriter writer = new FileWriter(csvFile);

        // 2. Write Column Headers
        for (int i = 0; i < model.getColumnCount(); i++) {
            writer.write("\"" + model.getColumnName(i) + "\"" + (i == model.getColumnCount() - 1 ? "" : ","));
        }
        writer.write("\n");

        // 3. Write Row Data
        for (int i = 0; i < model.getRowCount(); i++) {
            for (int j = 0; j < model.getColumnCount(); j++) {
                Object val = model.getValueAt(i, j);
                String cellStr = (val != null) ? val.toString().replace("\"", "\"\"") : "";
                writer.write("\"" + cellStr + "\"" + (j == model.getColumnCount() - 1 ? "" : ","));
            }
            writer.write("\n");
        }
        writer.close();

        // 4. Force VBScript to open the file directly in Microsoft Excel
        File vbsFile = File.createTempFile("openInExcel", ".vbs");
        vbsFile.deleteOnExit();

        FileWriter vbsWriter = new FileWriter(vbsFile);
        vbsWriter.write("Set objExcel = CreateObject(\"Excel.Application\")\n");
        vbsWriter.write("objExcel.Visible = True\n");
        vbsWriter.write("Set objWorkbook = objExcel.Workbooks.Open(\"" + csvFile.getAbsolutePath().replace("\\", "\\\\") + "\")\n");
        vbsWriter.close();

        Runtime.getRuntime().exec("wscript " + vbsFile.getAbsolutePath());

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Excel Launch Error: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void locationKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_locationKeyReleased
        // TODO add your handling code here:
     String loc = location.getText().trim();

    try {
        Connection con = connectionprovider.getCon();

        String sql = "SELECT donorID, name, fatherName, motherName, DOB, MobileNo, gender, email, bloodGroup, city, address "
                   + "FROM donor "
                   + "WHERE LOWER(city) LIKE ?";

        PreparedStatement ps = con.prepareStatement(sql);
        ps.setString(1, "%" + loc.toLowerCase() + "%");

        ResultSet rs = ps.executeQuery();
        jTable2.setModel(DbUtils.resultSetToTableModel(rs));

        rs.close();
        ps.close();
        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e);
    }
    }//GEN-LAST:event_locationKeyReleased

